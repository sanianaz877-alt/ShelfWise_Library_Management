-- Run in Supabase SQL Editor. Review/tighten policies before public production use.
create table if not exists public.books (
  id bigint generated by default as identity primary key,
  title text not null,
  author text not null,
  isbn text default '',
  category text default 'General',
  shelf text default '',
  total_copies integer not null default 1 check (total_copies >= 0),
  available_copies integer not null default 1 check (available_copies >= 0),
  cover text default '',
  created_at timestamptz not null default now()
);
create table if not exists public.students (
  id bigint generated by default as identity primary key,
  student_code text not null unique,
  name text not null,
  email text default '',
  department text default '',
  phone text default '',
  created_at timestamptz not null default now()
);
create table if not exists public.issued_books (
  id bigint generated by default as identity primary key,
  book_id bigint not null references public.books(id) on delete restrict,
  student_id bigint not null references public.students(id) on delete restrict,
  issue_date date not null default current_date,
  due_date date not null,
  return_date date,
  fine numeric(10,2) not null default 0,
  status text not null default 'issued' check (status in ('issued','returned')),
  created_at timestamptz not null default now()
);
alter table public.books enable row level security;
alter table public.students enable row level security;
alter table public.issued_books enable row level security;

